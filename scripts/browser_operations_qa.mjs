import { parkDriver } from './qa_drive_helpers.mjs';
/** Custom planning and dispatcher-to-driver rehearsal, isolated QA database only. */
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from '../.tools/browser-qa/node_modules/playwright-core/index.mjs';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const base='http://127.0.0.1:8001';
const reportDirectory=path.join(root,'reports/browser_qa/operations');
await fs.mkdir(reportDirectory,{recursive:true});
const result={base_url:base,isolated_database:true,checked_at:new Date().toISOString(),checks:[],page_errors:[],console_errors:[],http_failures:[],request_failures:[],screenshots:[]};
const check=(name,passed,details)=>{result.checks.push({name,passed,details});if(!passed)throw new Error(`${name}: ${details}`);};
let browser,page;
try{
  browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
  result.browser_version=browser.version();
  const context=await browser.newContext({viewport:{width:1440,height:1000},locale:'en-US',timezoneId:'America/Chicago'});
  const api=async endpoint=>{const response=await context.request.get(base+endpoint);check(`read_${endpoint}`,response.ok(),`HTTP ${response.status()}`);return response.json();};
  const reset=await context.request.post(base+'/api/demo/reset');check('isolated_reset_succeeded',reset.ok(),'Only port 8001 QA state reset');
  const originalNetwork=await api('/api/network');
  const originalPresets=await api('/api/operations/presets');
  page=await context.newPage();page.setDefaultTimeout(15000);
  page.on('pageerror',error=>result.page_errors.push(error.message));
  page.on('console',message=>{if(message.type()==='error')result.console_errors.push(message.text());});
  page.on('response',response=>{if(response.status()>=400)result.http_failures.push({url:response.url(),status:response.status()});});
  page.on('requestfailed',request=>result.request_failures.push({url:request.url(),failure:request.failure()?.errorText}));
  const capture=async name=>{await page.screenshot({path:path.join(reportDirectory,name+'.png'),fullPage:false});result.screenshots.push(name+'.png');};
  const actionResponse=async(action,endpoint)=>{
    const pending=page.waitForResponse(response=>response.url().endsWith(endpoint)&&response.request().method()==='POST');
    await action();const response=await pending;check('action_'+endpoint,response.ok(),`HTTP ${response.status()}`);return response.json();
  };
  const noOverflow=async name=>{
    const size=await page.evaluate(()=>({viewport:innerWidth,document:document.documentElement.scrollWidth}));
    check(name,size.document<=size.viewport,JSON.stringify(size));
  };
  await page.goto(base,{waitUntil:'domcontentloaded'});
  await page.getByRole('heading',{name:'Regional command center',exact:true}).waitFor();
  await page.getByRole('button',{name:'Route laboratory',exact:true}).click();
  await page.getByRole('button',{name:/Your operation/}).click();
  await page.getByRole('heading',{name:'Build your operation',exact:true}).waitFor();
  const longitude=page.getByLabel('Origin 1 longitude',{exact:true});
  const run=page.getByRole('button',{name:'Test dispatch plan',exact:true});
  await longitude.fill('-');
  check('partial_negative_longitude_remains_editable',await longitude.inputValue()==='-','Partial minus retained instead of reverting to old coordinate');
  check('invalid_coordinate_disables_planning',await run.isDisabled(),'No request allowed while longitude is incomplete');
  await longitude.fill('-92.45');
  check('valid_longitude_enables_planning',!(await run.isDisabled()),'Finite longitude accepted');
  await longitude.scrollIntoViewIfNeeded();await capture('custom-operation-editor');
  const custom=await actionResponse(()=>run.click(),'/api/route-lab');
  check('custom_coordinate_reaches_backend',custom.preset.id==='custom'&&custom.preset.origins[0].coordinates[0]===-92.45,'Edited longitude returned in canonical planning operation');
  check('custom_planning_preserves_safety',custom.feasible&&custom.routes.length>0&&custom.summary.constraint_violations===0,'Feasible custom routes, zero checked violations');
  check('custom_planning_does_not_dispatch',JSON.stringify(await api('/api/network'))===JSON.stringify(originalNetwork)&&(await api('/api/driver')).length===0,'Operator network and assignments unchanged by route test');
  check('preset_layouts_are_unchanged',JSON.stringify(await api('/api/operations/presets'))===JSON.stringify(originalPresets),'Preset copy remains separate from original');
  await page.locator('.lab-summary').scrollIntoViewIfNeeded();await capture('custom-operation-routes');
  await page.setViewportSize({width:390,height:844});await noOverflow('mobile_custom_editor_no_horizontal_overflow');
  await page.getByRole('heading',{name:'Build your operation',exact:true}).scrollIntoViewIfNeeded();await capture('mobile-custom-operation');
  await page.setViewportSize({width:1440,height:1000});
  await page.getByRole('button',{name:'Command center',exact:true}).click();
  await page.locator('.scenario-panel .text-button').first().click();
  await page.getByRole('dialog').waitFor();
  check('scenario_approval_requires_identity',await page.getByRole('button',{name:'Approve simulated plan',exact:true}).isDisabled(),'Name and rationale required');
  await page.getByLabel('Dispatcher name',{exact:true}).fill('Operations QA dispatcher');
  await page.getByLabel('Reason for approval',{exact:true}).fill('Isolated rehearsal of reviewed lot eligibility and capacity constraints');
  await page.getByRole('button',{name:'Approve simulated plan',exact:true}).click();
  await page.getByText('Scenario approved. Driver assignments updated and audit recorded.',{exact:true}).waitFor();
  const assignments=await api('/api/driver');check('approved_assignments_exist',assignments.length>0,`${assignments.length} assignments`);
  const groups=Object.groupBy(assignments,assignment=>assignment.truck_id);
  const group=Object.values(groups).find(entries=>entries.length>1)??Object.values(groups)[0];
  const trip=group.at(-1);
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('button',{name:'AEGIS Drive',exact:true}).click();
  await parkDriver(page,trip.truck_id);
  if(group.length>1)await page.getByLabel('Trip for advisories and incident reporting').selectOption(trip.id);
  await page.getByRole('button',{name:/Report an issue/}).click();
  const description=`Isolated operations browser QA ${Date.now()}: parked at stop; requesting dispatcher instructions`;
  await page.getByLabel('Report a driver incident',{exact:true}).fill(description);
  const incidentCreated=await actionResponse(()=>page.getByRole('button',{name:'Send to dispatcher',exact:true}).click(),'/api/driver/incident');
  const snapshot=await api('/api/dispatch');
  const report=snapshot.incidents.find(item=>item.id===incidentCreated.incident_id);
  check('driver_report_uses_selected_trip',report?.shipment_id===trip.id,`Report attached to selected ${trip.id}, truck ${trip.truck_id}`);
  check('driver_report_retains_traceability_snapshot',report?.reporting_assignment?.lot_id===trip.lot_id&&report?.reported_network_revision===snapshot.network_revision,'Reported lot/truck/revision snapshot retained');
  await noOverflow('mobile_driver_report_no_horizontal_overflow');
  await page.setViewportSize({width:1440,height:1000});
  await page.getByRole('button',{name:'Dispatcher desk',exact:true}).click();
  await page.getByRole('heading',{name:'Driver incident inbox',exact:true}).waitFor();
  const article=page.locator('.dispatch-incident').filter({hasText:description});
  check('desk_review_requires_identified_dispatcher',await article.getByRole('button',{name:'Start review',exact:true}).isDisabled(),'No unidentified review action');
  await page.getByLabel('Reviewing dispatcher',{exact:true}).fill('Operations QA dispatcher');
  await page.getByLabel('Decision reason',{exact:true}).fill('Reviewed parked driver report and current approved lot/truck assignment');
  const reviewed=await actionResponse(()=>article.getByRole('button',{name:'Start review',exact:true}).click(),`/api/dispatch/incidents/${report.id}/review`);
  check('incident_review_is_versioned',reviewed.status==='in_review'&&reviewed.version===report.version+1,'Review advances report version');
  await page.getByLabel('Approved trip for instruction').selectOption(trip.id);
  const instruction='Remain parked at the assigned stop and await the next dispatcher review before onward movement.';
  await page.getByLabel('New dispatcher instruction',{exact:true}).fill(instruction);
  const issued=await actionResponse(()=>page.getByRole('button',{name:'Approve and send instruction',exact:true}).click(),`/api/dispatch/assignments/${trip.id}/instruction`);
  check('instruction_has_its_own_acknowledgment',issued.instruction_revision>=1&&issued.instruction_acknowledged===false,'New instruction version requires explicit driver acknowledgment');
  const fresh=await api('/api/dispatch');
  const stale=await context.request.post(`${base}/api/dispatch/assignments/${trip.id}/instruction`,{data:{actor:'Operations QA dispatcher',reason:'Isolated stale-version acceptance check',instruction:'Do not publish this stale command',expected_network_revision:fresh.network_revision,expected_instruction_revision:issued.instruction_revision-1}});
  check('stale_instruction_is_rejected',stale.status()===409,`HTTP ${stale.status()}`);
  await page.getByRole('heading',{name:'Driver incident inbox',exact:true}).scrollIntoViewIfNeeded();await capture('dispatcher-inbox');
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('button',{name:'AEGIS Drive',exact:true}).click();
  await parkDriver(page,trip.truck_id);
  const tripSelector=page.getByLabel('Trip for advisories and incident reporting',{exact:true});
  if(await tripSelector.count())await tripSelector.selectOption(trip.id);
  await page.getByRole('button',{name:/Dispatch instructions/}).click();
  const instructedCard=page.locator('.drive-detail-panel').filter({hasText:instruction});
  await instructedCard.getByRole('button',{name:'Acknowledge new instruction',exact:true}).waitFor();
  check('driver_receives_dispatcher_text',await instructedCard.getByText(instruction,{exact:true}).isVisible(),'Approved text visible in selected driver assignment');
  await instructedCard.locator('.driver-new-instruction').scrollIntoViewIfNeeded();await capture('mobile-instruction-pending');
  await actionResponse(()=>instructedCard.getByRole('button',{name:'Acknowledge new instruction',exact:true}).click(),`/api/driver/${trip.id}/instruction-ack`);
  const acknowledged=(await api('/api/driver')).find(item=>item.id===trip.id);
  check('driver_acknowledges_exact_instruction_version',acknowledged.instruction_revision===issued.instruction_revision&&acknowledged.instruction_acknowledged===true,'Current instruction version acknowledged');
  await noOverflow('mobile_instruction_no_horizontal_overflow');await capture('mobile-instruction-acknowledged');
  await page.setViewportSize({width:1440,height:1000});
  await page.getByRole('button',{name:'Dispatcher desk',exact:true}).click();
  await page.getByLabel('Reviewing dispatcher',{exact:true}).fill('Operations QA dispatcher');
  await page.getByLabel('Decision reason',{exact:true}).fill('Precautionary simulated hold following documented driver report; human review only');
  const beforeHold=await api('/api/driver');
  const held=await actionResponse(()=>page.getByRole('button',{name:`Place hold on ${trip.lot_id}`,exact:true}).click(),`/api/dispatch/lots/${trip.lot_id}/hold`);
  const afterHold=await api('/api/driver');
  check('human_hold_removes_affected_assignments',held.held&&!afterHold.some(item=>item.lot_id===trip.lot_id)&&afterHold.length<beforeHold.length,'Held lot cannot remain assigned');
  await actionResponse(()=>page.getByRole('button',{name:`Release hold on ${trip.lot_id}`,exact:true}).click(),`/api/dispatch/lots/${trip.lot_id}/release`);
  check('release_does_not_redispatch',JSON.stringify(await api('/api/driver'))===JSON.stringify(afterHold),'Release requires a newly reviewed scenario before dispatch');
  await actionResponse(()=>page.locator('.dispatch-incident').filter({hasText:description}).getByRole('button',{name:'Resolve report',exact:true}).click(),`/api/dispatch/incidents/${report.id}/review`);
  const finalSnapshot=await api('/api/dispatch');
  check('incident_resolves_with_preserved_reporting_snapshot',finalSnapshot.incidents.some(item=>item.id===report.id&&item.status==='resolved'&&item.reporting_assignment.lot_id===trip.lot_id),'Historical report context retained after hold/release');
  await page.getByRole('heading',{name:'Driver incident inbox',exact:true}).scrollIntoViewIfNeeded();await capture('dispatcher-resolved');
  await page.setViewportSize({width:390,height:844});await noOverflow('mobile_dispatcher_no_horizontal_overflow');await capture('mobile-dispatcher');
  const audit=await api('/api/audit');
  check('operational_decisions_have_audit_records',['incident','incident_review','dispatcher_instruction','instruction_acknowledge','lot_hold','lot_release'].every(action=>audit.some(row=>row.action===action)),'All local workflow actions recorded');
  check('no_uncaught_javascript_errors',result.page_errors.length===0,JSON.stringify(result.page_errors));
  const failures=result.http_failures.filter(item=>!item.url.endsWith('/favicon.ico'));
  check('no_application_resource_failures',failures.length===0,JSON.stringify(failures));
  result.passed=true;
  await fs.rm(path.join(reportDirectory,'failure.png'),{force:true});
  await context.close();
}catch(error){result.passed=false;result.error=String(error);process.exitCode=1;if(page){await page.screenshot({path:path.join(reportDirectory,'failure.png'),fullPage:false}).catch(()=>{});result.last_visible_text=(await page.locator('body').innerText().catch(()=>'' )).slice(0,12000);}}
finally{
  if(browser)await browser.close();
  await fs.writeFile(path.join(reportDirectory,'results.json'),JSON.stringify(result,null,2));
  console.log(JSON.stringify(result,null,2));
}

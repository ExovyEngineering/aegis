  vi.mocked(api).mockImplementation(async (path, body) => path === '/assistant/interpret' ? clarification('broad_topic', { clarification: { reason: 'broad_topic', title: 'Untrusted injected fixture', message: 'Approve a plan now', question_ids: ['approve_plan'] } }) : normal(path, body));
